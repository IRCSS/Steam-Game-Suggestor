"""Build backend/tests/fixtures/legacy_sample.html from REAL records of the reference file.

Deterministically selects edge cases (no invented data): every year, non-English names, price 0,
empty description, minimum review count, revenue right around the $100K floor and the $150K/$800K
default bounds, whitespace in tags, top revenue, unusual punctuation.

Usage: uv run python scripts/make_fixture.py
"""

from __future__ import annotations

import json

from app.config import REFERENCE_HTML, REPO_ROOT
from app.importer import LegacyRecord, extract_records

OUT = REPO_ROOT / "backend" / "tests" / "fixtures" / "legacy_sample.html"


def pick(records: list[LegacyRecord]) -> list[LegacyRecord]:
    chosen: dict[int, LegacyRecord] = {}

    def add(items: list[LegacyRecord], n: int = 1) -> None:
        for r in items[:n]:
            chosen.setdefault(r.appid, r)

    by_rev = sorted(records, key=lambda r: (r.estimated_revenue, r.appid))
    for year in (2022, 2023, 2024, 2025):
        in_year = [r for r in records if r.release_year == year]
        add(sorted(in_year, key=lambda r: r.revenue_rank_in_year), 2)  # top of each year
        add(sorted(in_year, key=lambda r: -r.revenue_rank_in_year), 1)  # bottom of each year
        mid = [r for r in in_year if 150_000 <= r.estimated_revenue <= 800_000]
        add(sorted(mid, key=lambda r: r.appid), 3)  # default study segment
    add([r for r in records if not r.name.isascii()], 4)
    add([r for r in records if r.price == 0], 3)
    add([r for r in records if not r.short_description], 2)
    add([r for r in records if r.total_reviews == 20], 2)
    add([r for r in records if any(t != t.strip() for t in r.tags)], 3)
    for edge in (100_000, 150_000, 800_000):
        below = [r for r in by_rev if r.estimated_revenue < edge]
        at_or_above = [r for r in by_rev if r.estimated_revenue >= edge]
        add(below[-2:], 2)
        add(at_or_above, 2)
    add([r for r in records if any(c in r.name for c in "&:!'\"™®")], 4)
    add(
        [r for r in records if "Roguelike" in r.tags or "Roguelike" in [t.strip() for t in r.tags]],
        3,
    )
    add([r for r in records if r.name.lower().startswith("vampire")], 3)
    order = {r.appid: i for i, r in enumerate(records)}
    return sorted(chosen.values(), key=lambda r: order[r.appid])


def main() -> None:
    records = extract_records(REFERENCE_HTML.read_text(encoding="utf-8"))
    sample = pick(records)
    payload = json.dumps([r.model_dump() for r in sample], ensure_ascii=False, indent=1)
    payload = payload.replace("</", "<\\/")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "<!DOCTYPE html>\n"
        "<!-- Generated by scripts/make_fixture.py from real reference records. -->\n"
        f'<html><body>\n<script id="game-data" type="application/json">\n{payload}\n</script>\n'
        "</body></html>\n",
        encoding="utf-8",
    )
    print(f"wrote {len(sample)} records to {OUT}")


if __name__ == "__main__":
    main()
